import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
// npm install installs TypeScript via existing Evolve devDependencies.
const ts=require('typescript');
const source=readFileSync(new URL('../src/lib/orchestrator/core.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{fileName:'core.ts',compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});
const {weekMonday,daysBefore,suggestions,dayGuidance,totalWithMinutes}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputText).toString('base64'));
assert.equal(weekMonday('2026-10-21'),'2026-10-19');
assert.equal(weekMonday('2026-10-25'),'2026-10-19');
assert.equal(weekMonday('2026-10-26'),'2026-10-26');
assert.equal(weekMonday('2027-01-01'),'2026-12-28');
assert.equal(daysBefore('2026-10-21',6),'2026-10-15');
assert.throws(()=>weekMonday('2026-02-30'));
assert.equal(dayGuidance({energy:1,workoutToday:true,mealSaved:true,coachDue:2,coachDone:1}).title,'Giornata con poca energia');
assert.equal(dayGuidance({energy:3,workoutToday:true,mealSaved:false,coachDue:2,coachDone:0}).href,'/allenamento');
assert.equal(dayGuidance({energy:3,workoutToday:false,mealSaved:false,coachDue:0,coachDone:0}).href,'/mealprep');
assert.equal(totalWithMinutes([{duration_minutes:30},{duration_minutes:'20'},{duration_minutes:-20},{duration_minutes:9999}]),50);
const x={checkinDays:2,lowEnergyDays:2,workoutCount:0,workoutMinutes:0,plannedMeals:null,coachDone:0,coachSkipped:2,coachScheduled:3};
const tips=suggestions(x);
assert(tips.length>=2&&tips.length<=4);
assert(tips.some(s=>s.id==='recupero'));
assert(tips.some(s=>s.id==='pasti'));
assert(tips.every(s=>s.action.length>=8&&s.reason.length>10));
const robust=suggestions({...x,checkinDays:7,lowEnergyDays:0,workoutCount:4,plannedMeals:5,coachSkipped:0});
assert(robust.some(s=>s.id==='continuita'));
assert(!robust.some(s=>s.id==='movimento'));
assert(!robust.some(s=>s.id==='pasti'));
for(const p of ['src/app/api/orchestrator/overview/route.ts','src/app/api/orchestrator/focus/route.ts','src/app/(app)/giornata/page.tsx','src/app/(app)/revisione/page.tsx','src/components/orchestrator-overview.tsx','src/components/orchestrator-review.tsx','src/app/orchestrator.css','supabase/migrations/202610210001_orchestrator.sql'])assert(existsSync(new URL('../'+p,import.meta.url)),p);
const sql=readFileSync(new URL('../supabase/migrations/202610210001_orchestrator.sql',import.meta.url),'utf8');
assert(readFileSync(new URL('../src/app/api/orchestrator/focus/route.ts',import.meta.url),'utf8').includes("m.data.note.trim().length<3"));
assert(sql.includes('enable row level security')&&sql.includes('auth.uid()')&&sql.includes('primary key (user_id, week_start)'));
const api=readFileSync(new URL('../src/app/api/orchestrator/overview/route.ts',import.meta.url),'utf8');
for(const tbl of ['evolve_workouts','evolve_meal_plans','evolve_daily_states','evolve_coach_commitments','evolve_coach_logs','evolve_weekly_focus'])assert(api.includes(tbl),tbl);
